#!/usr/bin/env python3
"""Generate the ecosystem status diagram from ecosystem-status.yaml.

A hand-drawn diagram drifts. This one is generated from the same status data that the claims
register checks, so what the diagram says and what the register measures cannot part quietly.

  --write             regenerate diagrams/status.mmd and the marked block in each README
  --check             fail when either is not what --write would produce
  --verify-evidence   fail when a component is `live` and its evidence claim is not PASS in
                      claims/STATUS.md (a FAIL, UNVERIFIED, or missing result all fail)

--check and --verify-evidence are separate on purpose. The first needs only this repository.
The second reads the last run of the claims verifier, so it can fail because of drift in
other repositories, which is the point of it.

No network, no clock, no randomness: the same input gives the same bytes. Exit 0 when clean,
1 when a check fails, 2 when an input cannot be read.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = "bawbel/ecosystem-status/v1"

STATUS_FILE = "ecosystem-status.yaml"
DIAGRAM_FILE = "diagrams/status.mmd"
RESULTS_FILE = "claims/STATUS.md"
REGISTER_FILE = "claims/register.yaml"
README_FILES = ("profile/README.md",)
DEFAULT_RESULTS_URL = "https://github.com/bawbel/.github/blob/main/claims/STATUS.md"

BEGIN = "<!-- status-diagram:begin (generated by scripts/render_status.py, do not edit) -->"
END = "<!-- status-diagram:end -->"

STATES = ("live", "pre-release", "designed", "offline", "not-built")
STATE_CLASS = {
    "live": "live",
    "pre-release": "pre",
    "designed": "des",
    "offline": "off",
    "not-built": "nb",
}
# Colour is never the only cue: each state is also written in the node, and the three
# states that are not serving or not shipped have different dash patterns.
STATE_STYLE: dict[str, dict[str, str]] = {
    "live": {"fill": "#E1F5EE", "stroke": "#0F6E56", "color": "#04342C"},
    "pre-release": {"fill": "#FAEEDA", "stroke": "#854F0B", "color": "#412402"},
    "designed": {
        "fill": "#FAEEDA", "stroke": "#854F0B", "color": "#412402", "stroke-dasharray": "3 3",
    },
    "offline": {
        "fill": "#FCEBEB", "stroke": "#A32D2D", "color": "#501313", "stroke-dasharray": "2 4",
    },
    "not-built": {
        "fill": "#F1EFE8", "stroke": "#5F5E5A", "color": "#2C2C2A", "stroke-dasharray": "5 4",
    },
}
OUTSIDE_STYLE = {"stroke-dasharray": "8 3"}

ID_RE = re.compile(r"^[a-z][a-z0-9_]{0,31}$")
CLAIM_RE = re.compile(r"^C-\d+$")
RESERVED = {
    "end", "graph", "subgraph", "flowchart", "class", "classdef", "click", "style", "default",
    "legend", "bawbel_boundary",
}
RESULT_ROW = re.compile(r"^\|\s*(C-\d+)\s*\|.*?\*\*(PASS|FAIL|UNVERIFIED)\*\*", re.MULTILINE)


class StatusError(Exception):
    """The status file, or a file it depends on, is not usable."""


# ---------------------------------------------------------------- input


def validate(data: Any, claim_ids: set[str]) -> dict[str, Any]:
    """Check the shape of ecosystem-status.yaml. Returns it unchanged."""
    if not isinstance(data, dict) or data.get("schema") != SCHEMA:
        raise StatusError(f"schema must be {SCHEMA}")
    components = data.get("components")
    if not isinstance(components, list) or not components:
        raise StatusError("no components")
    seen: set[str] = set()
    for index, comp in enumerate(components, start=1):
        if not isinstance(comp, dict):
            raise StatusError(f"component {index} is not a mapping")
        cid = comp.get("id")
        if not isinstance(cid, str) or not ID_RE.match(cid):
            raise StatusError(f"component {index}: invalid id {cid!r}, use [a-z][a-z0-9_]*")
        if cid in RESERVED:
            raise StatusError(f"{cid}: reserved word in Mermaid or in this diagram")
        if cid in seen:
            raise StatusError(f"{cid}: duplicate id")
        seen.add(cid)
        if not isinstance(comp.get("label"), str) or not comp["label"].strip():
            raise StatusError(f"{cid}: label is required")
        if comp.get("state") not in STATES:
            raise StatusError(f"{cid}: unknown state {comp.get('state')!r}, use one of {STATES}")
        evidence = comp.get("evidence")
        if not isinstance(evidence, str) or not CLAIM_RE.match(evidence):
            raise StatusError(f"{cid}: evidence must be a claim id such as C-01")
        if evidence not in claim_ids:
            raise StatusError(f"{cid}: evidence {evidence} is not in the register")
        if comp.get("boundary") not in (None, "outside"):
            raise StatusError(f"{cid}: boundary must be 'outside' or absent")
    for edge in data.get("edges") or []:
        if not isinstance(edge, (list, tuple)) or len(edge) != 2:
            raise StatusError(f"edge {edge!r} must be two component ids")
        for end in edge:
            if end not in seen:
                raise StatusError(f"edge {list(edge)} names an unknown component {end!r}")
    url = data.get("results_url", DEFAULT_RESULTS_URL)
    if not isinstance(url, str) or not url.startswith("https://"):
        raise StatusError("results_url must be an https URL")
    return data


def parse_results(text: str) -> dict[str, str]:
    """claim id -> PASS | FAIL | UNVERIFIED, read from the table in claims/STATUS.md."""
    return {m.group(1): m.group(2) for m in RESULT_ROW.finditer(text)}


def evidence_errors(data: dict[str, Any], results: dict[str, str]) -> list[str]:
    """One message per live component whose evidence claim is not PASS."""
    errors = []
    for comp in data["components"]:
        if comp["state"] != "live":
            continue
        claim = comp["evidence"]
        result = results.get(claim)
        if result is None:
            errors.append(f"{comp['id']}: state live but {claim} has no result in {RESULTS_FILE}")
        elif result != "PASS":
            errors.append(f"{comp['id']}: state live but {claim} is {result} in {RESULTS_FILE}")
    return errors


# ---------------------------------------------------------------- output


def _escape(text: str) -> str:
    """Mermaid entity codes, so a label can never open a tag or close its own quote."""
    for raw, code in (("&", "#amp;"), ('"', "#quot;"), ("<", "#lt;"), (">", "#gt;")):
        text = text.replace(raw, code)
    return text


def _style(props: dict[str, str]) -> str:
    return ",".join(f"{key}:{value}" for key, value in props.items())


def render(data: dict[str, Any]) -> str:
    """The Mermaid diagram. Deterministic: file order, no clock, no randomness."""
    components = data["components"]
    outside = [c for c in components if c.get("boundary") == "outside"]
    inside = [c for c in components if c.get("boundary") != "outside"]

    def node(comp: dict[str, Any], indent: str) -> str:
        label = f"{_escape(comp['label'])}<br/><small>{comp['state']}</small>"
        return f'{indent}{comp["id"]}["{label}"]'

    lines = ["flowchart TD"]
    lines += [node(c, "    ") for c in outside]
    lines.append('    subgraph bawbel_boundary["Bawbel"]')
    lines += [node(c, "        ") for c in inside]
    lines.append("    end")
    for source, target in data.get("edges") or []:
        lines.append(f"    {source} --> {target}")
    states = ", ".join(STATES)
    lines.append(
        '    legend["<small>Legend: '
        f"{states}. A live component has a passing evidence claim in claims/STATUS.md. "
        'Long dashes: separate org.</small>"]'
    )
    for state in STATES:
        lines.append(f"    classDef {STATE_CLASS[state]} {_style(STATE_STYLE[state])}")
    lines.append(f"    classDef outside {_style(OUTSIDE_STYLE)}")
    lines.append("    classDef key fill:#FFFFFF,stroke:#B4B2A9,color:#2C2C2A")
    for state in STATES:
        members = [c["id"] for c in components if c["state"] == state]
        if members:
            lines.append(f"    class {','.join(members)} {STATE_CLASS[state]}")
    for comp in outside:
        lines.append(f"    class {comp['id']} outside")
    lines.append("    class legend key")
    return "\n".join(lines) + "\n"


def readme_block(data: dict[str, Any], mermaid: str) -> str:
    """What sits between the markers in a README: the diagram and a legend with a link."""
    url = data.get("results_url", DEFAULT_RESULTS_URL)
    legend = (
        "Legend: **live** means the component's evidence claim passes in "
        f"[claims/STATUS.md]({url}). "
        "States: live, pre-release, designed, offline, not-built. "
        "Long dashes: a separate organization."
    )
    return f"{BEGIN}\n```mermaid\n{mermaid}```\n\n{legend}\n{END}"


def replace_block(text: str, block: str, where: str) -> str:
    start, end = text.find(BEGIN), text.find(END)
    if start == -1 or end == -1 or end < start:
        raise StatusError(f"{where} has no {BEGIN!r} ... {END!r} markers")
    return text[:start] + block + text[end + len(END):]


# ---------------------------------------------------------------- command


def _read(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except OSError as exc:
        raise StatusError(f"cannot read {path}: {exc}") from exc


def load(root: Path) -> dict[str, Any]:
    try:
        raw = yaml.safe_load(_read(root / STATUS_FILE))
        register = yaml.safe_load(_read(root / REGISTER_FILE))
    except yaml.YAMLError as exc:
        raise StatusError(f"not valid YAML: {exc}") from exc
    claims = register.get("claims") if isinstance(register, dict) else None
    if not isinstance(claims, list):
        raise StatusError(f"{REGISTER_FILE} has no claims list")
    return validate(raw, {c["id"] for c in claims if isinstance(c, dict) and "id" in c})


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--readme", action="append", default=None, metavar="PATH",
                        help=f"README with the markers, relative to --root (default {README_FILES})")
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--verify-evidence", action="store_true")
    args = parser.parse_args(argv)
    root = args.root
    readmes = args.readme or list(README_FILES)
    modes = [m for m in ("write", "check", "verify_evidence") if getattr(args, m)] or ["write"]

    try:
        data = load(root)
        mermaid = render(data)
        block = readme_block(data, mermaid)
        wanted = {DIAGRAM_FILE: mermaid}
        for name in readmes:
            wanted[name] = replace_block(_read(root / name), block, name)
    except StatusError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    status = 0
    if "write" in modes:
        for name, text in wanted.items():
            target = root / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8")
        print(f"wrote {', '.join(wanted)}")
    if "check" in modes:
        for name, text in wanted.items():
            target = root / name
            current = target.read_text(encoding="utf-8") if target.is_file() else None
            if current != text:
                print(f"error: {name} is not current; run python scripts/render_status.py --write",
                      file=sys.stderr)
                status = 1
        if status == 0:
            print(f"current: {', '.join(wanted)}")
    if "verify_evidence" in modes:
        try:
            results = parse_results(_read(root / RESULTS_FILE))
        except StatusError as exc:
            print(f"error: {exc}", file=sys.stderr)
            return 2
        errors = evidence_errors(data, results)
        for message in errors:
            print(f"error: {message}", file=sys.stderr)
        if errors:
            status = 1
        else:
            live = sum(1 for c in data["components"] if c["state"] == "live")
            print(f"evidence: {live} live component(s), every evidence claim is PASS")
    return status


if __name__ == "__main__":
    sys.exit(main())
