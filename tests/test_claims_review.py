"""Tests for scripts/claims_review.py and the monthly review workflow. No network."""

from __future__ import annotations

import importlib.util
import re
import sys
from pathlib import Path

import pytest
import yaml

ROOT = Path(__file__).resolve().parent.parent
SPEC = importlib.util.spec_from_file_location("claims_review", ROOT / "scripts/claims_review.py")
cr = importlib.util.module_from_spec(SPEC)
sys.modules["claims_review"] = cr
SPEC.loader.exec_module(cr)

STATUS = """# Claims status

Generated by `scripts/verify_claims.py` from `claims/register.yaml`. Do not edit by hand.

- Run: 2026-10-23, mode: online
- Result: 2 FAIL, 2 UNVERIFIED, 1 PASS

| ID | Claim | Result | Measured | Expected | Evidence |
|---|---|---|---|---|---|
| C-01 | AVE records published | **FAIL** | 87 | 87 | records at ave@6b9f174 (16 problem(s)) |
| C-02 | AVE records with scanner metadata (scanner/ave_meta.py) | **PASS** | 51 | 51 | keys |
| C-07 | Detection rules (pattern + YARA + Semgrep) | **FAIL** | 120 | 120 | pattern 40 |
| C-14 | The registry is designed, not built | **UNVERIFIED** | None | designed | private |
| C-17 | PiranhaDB public endpoint count | **UNVERIFIED** | 21 | None | 21 route decorators |

## Unverified

- C-14: source registry unavailable

## Details

### C-01 AVE records published: FAIL

- FAIL: scanner:README.md:16: states 51, register expects 87
"""


def section(body: str, heading: str) -> str:
    """The text of one `## heading` section of the issue body."""
    match = re.search(rf"^## {re.escape(heading)}.*?\n(.*?)(?=^## |^<details>|\Z)", body, re.M | re.S)
    assert match, f"no section {heading!r} in:\n{body}"
    return match.group(1)


# ---------------------------------------------------------------- parsing


def test_parse_rows_reads_id_claim_and_result():
    rows = cr.parse_rows(STATUS)
    assert [(r.id, r.result) for r in rows] == [
        ("C-01", "FAIL"), ("C-02", "PASS"), ("C-07", "FAIL"),
        ("C-14", "UNVERIFIED"), ("C-17", "UNVERIFIED"),
    ]
    assert rows[1].claim == "AVE records with scanner metadata (scanner/ave_meta.py)"
    assert rows[2].claim == "Detection rules (pattern + YARA + Semgrep)"


def test_the_details_section_is_not_mistaken_for_rows():
    assert len(cr.parse_rows(STATUS)) == 5


@pytest.mark.parametrize("month", ["2026-10", "2027-01", "2026-12"])
def test_valid_months(month):
    assert cr.title(month) == f"Claims review {month}"


@pytest.mark.parametrize("month", ["2026-13", "2026-00", "26-10", "2026-1", "October", "", "2026-10-01"])
def test_invalid_months_are_rejected(month):
    with pytest.raises(ValueError, match="month"):
        cr.title(month)


# ---------------------------------------------------------------- the body


def test_every_failing_claim_is_listed_by_id_and_text():
    fails = section(cr.build_body(STATUS, "2026-10"), "FAIL (2)")
    assert "C-01" in fails and "AVE records published" in fails
    assert "C-07" in fails and "Detection rules" in fails
    assert "C-02" not in fails and "C-14" not in fails


def test_every_unverified_claim_is_listed_so_none_stays_silent():
    unverified = section(cr.build_body(STATUS, "2026-10"), "UNVERIFIED (2)")
    assert "C-14" in unverified and "C-17" in unverified
    assert "C-01" not in unverified


def test_a_passing_claim_is_not_listed_in_either_section():
    body = cr.build_body(STATUS, "2026-10")
    assert "C-02" not in section(body, "FAIL (2)") + section(body, "UNVERIFIED (2)")


def test_counts_come_from_the_rows():
    body = cr.build_body(STATUS, "2026-10")
    assert "2 FAIL, 2 UNVERIFIED, 1 PASS" in body


def test_empty_sections_say_none():
    clean = STATUS.replace("**FAIL**", "**PASS**").replace("**UNVERIFIED**", "**PASS**")
    body = cr.build_body(clean, "2026-10")
    assert "0 FAIL, 0 UNVERIFIED, 5 PASS" in body
    assert section(body, "FAIL (0)").strip() == "None."
    assert section(body, "UNVERIFIED (0)").strip() == "None."


def test_the_body_says_it_changes_nothing_and_who_closes_failures():
    body = cr.build_body(STATUS, "2026-10")
    assert "changes nothing" in body
    assert "fixing the surface or the register" in body


def test_the_full_report_is_included():
    body = cr.build_body(STATUS, "2026-10")
    assert "<details>" in body and "</details>" in body
    assert "states 51, register expects 87" in body


def test_a_status_file_with_no_claims_is_an_error_not_a_clean_issue():
    with pytest.raises(ValueError, match="no claims"):
        cr.build_body("# Claims status\n\nnothing here\n", "2026-10")


def test_a_long_report_is_cut_but_the_lists_survive():
    padding = "\n".join(f"- FAIL: scanner:README.md:{i}: states 51, register expects 87" for i in range(5000))
    body = cr.build_body(STATUS + padding, "2026-10")
    assert len(body) <= cr.MAX_BODY
    assert "C-14" in section(body, "UNVERIFIED (2)")
    assert "cut" in body


def test_the_title_is_exactly_the_runbook_title():
    assert cr.title("2026-10") == "Claims review 2026-10"


# ---------------------------------------------------------------- the command


def test_main_prints_the_body_and_the_title(tmp_path, capsys):
    path = tmp_path / "STATUS.md"
    path.write_text(STATUS)
    assert cr.main(["--status", str(path), "--month", "2026-10"]) == 0
    assert "## FAIL (2)" in capsys.readouterr().out
    assert cr.main(["--print-title", "--month", "2026-10"]) == 0
    assert capsys.readouterr().out.strip() == "Claims review 2026-10"


def test_main_exits_2_on_a_missing_file_or_bad_month(tmp_path, capsys):
    assert cr.main(["--status", str(tmp_path / "nope.md"), "--month", "2026-10"]) == 2
    path = tmp_path / "STATUS.md"
    path.write_text(STATUS)
    assert cr.main(["--status", str(path), "--month", "2026-13"]) == 2
    assert "error" in capsys.readouterr().err


def test_the_script_has_no_network_code():
    source = (ROOT / "scripts/claims_review.py").read_text()
    assert not re.search(r"^\s*(import|from)\s+(socket|urllib|http|requests|ssl|subprocess)\b", source, re.M)


# ---------------------------------------------------------------- the workflow

WORKFLOW = ROOT / ".github/workflows/claims-review.yml"


def workflow() -> dict:
    data = yaml.safe_load(WORKFLOW.read_text())
    data["on"] = data.pop(True, data.get("on"))  # YAML reads a bare `on` as True
    return data


def test_the_workflow_runs_on_the_first_of_the_month_and_by_hand_only():
    triggers = workflow()["on"]
    assert set(triggers) == {"schedule", "workflow_dispatch"}
    cron = triggers["schedule"][0]["cron"].split()
    assert cron[2] == "1" and cron[3:] == ["*", "*"], "day of month 1, every month"


def test_the_workflow_asks_for_no_more_than_it_needs():
    assert workflow()["permissions"] == {"contents": "read", "issues": "write"}


def test_every_action_is_pinned_by_a_full_commit_sha():
    uses = re.findall(r"^\s*-?\s*uses:\s*(\S+)", WORKFLOW.read_text(), re.M)
    assert uses, "the workflow uses at least checkout"
    for ref in uses:
        assert re.fullmatch(r"[\w./-]+@[0-9a-f]{40}", ref), ref


def test_the_workflow_checks_for_an_existing_issue_before_creating_one():
    text = WORKFLOW.read_text()
    assert text.index("gh issue list") < text.index("gh issue create")


def test_the_workflow_does_not_use_a_personal_token_or_secrets():
    text = WORKFLOW.read_text()
    assert "secrets." not in text
    assert "github.token" in text
